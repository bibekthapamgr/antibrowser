#!/usr/bin/env node
/**
 * Dependency and license inventory (milestone 01, step 2).
 * Writes docs/licenses/inventory.json and docs/licenses/summary.md, and exits non-zero if any dependency
 * has a license outside the allow-list (copyleft licenses need a human decision before they ship in the
 * desktop app).
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const ALLOWED = [
  'MIT',
  'MIT-0',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  'ISC',
  '0BSD',
  'Zlib',
  'Unicode-3.0',
  'Unicode-DFS-2016',
  'BSL-1.0',
  'CC0-1.0',
  'Unlicense',
  'BlueOak-1.0.0',
  'CC-BY-4.0',
  'Python-2.0',
  'MPL-2.0',
  'CDLA-Permissive-2.0',
  'bzip2-1.0.6',
  'OFL-1.1',
];
/** Workspace packages are ours (UNLICENSED until the company chooses a license). */
const OWN = (name) => name.startsWith('@pb/') || name.startsWith('pb-') || name === 'project-browser';

const allowedExpr = (expr) => {
  if (!expr) return false;
  const cleaned = expr.replace(/[()]/g, ' ').replace(/\s+/g, ' ').trim();
  // "A OR B": acceptable if any alternative is allowed; "A AND B": all must be allowed.
  if (/ OR |\//.test(cleaned)) return cleaned.split(/ OR |\//).some((p) => allowedExpr(p.trim()));
  if (/ AND /.test(cleaned)) return cleaned.split(/ AND /).every((p) => allowedExpr(p));
  return ALLOWED.includes(cleaned.replace(/ WITH .*/, ''));
};

// ---- npm (production + dev) via pnpm
const pnpmJson = JSON.parse(
  execFileSync('pnpm', ['licenses', 'list', '--json'], { cwd: ROOT, encoding: 'utf8', maxBuffer: 64e6 }),
);
const npm = [];
for (const [license, pkgs] of Object.entries(pnpmJson)) {
  for (const p of pkgs)
    for (const v of p.versions ?? [p.version])
      npm.push({ ecosystem: 'npm', name: p.name, version: v, license });
}

// ---- cargo
const meta = JSON.parse(
  execFileSync('cargo', ['metadata', '--format-version', '1', '--locked'], {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 256e6,
  }),
);
const cargo = meta.packages.map((p) => ({
  ecosystem: 'cargo',
  name: p.name,
  version: p.version,
  license: p.license ?? p.license_file ?? 'UNKNOWN',
}));

const all = [...npm, ...cargo]
  .filter((d) => !OWN(d.name))
  .sort((a, b) => `${a.ecosystem}${a.name}`.localeCompare(`${b.ecosystem}${b.name}`));
const flagged = all.filter((d) => !allowedExpr(d.license));

const counts = {};
for (const d of all) counts[d.license] = (counts[d.license] ?? 0) + 1;

const outDir = join(ROOT, 'docs', 'licenses');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  join(outDir, 'inventory.json'),
  `${JSON.stringify({ generated_at: new Date().toISOString(), dependencies: all }, null, 2)}\n`,
);
const md = [
  '# Dependency license inventory',
  '',
  `Generated by \`pnpm run licenses\`. ${all.length} third-party packages (npm ${npm.filter((d) => !OWN(d.name)).length}, cargo ${cargo.filter((d) => !OWN(d.name)).length}).`,
  'Cargo counts include platform-specific crates for all targets (Windows/macOS/Linux), not only what ships on one OS.',
  '',
  '| License expression | Packages |',
  '|---|---|',
  ...Object.entries(counts)
    .sort((a, b) => b[1] - a[1])
    .map(([l, n]) => `| ${l} | ${n} |`),
  '',
  flagged.length ? '## Needs review (outside the allow-list)' : '## Needs review: none',
  ...flagged.map((d) => `- ${d.ecosystem} \`${d.name}@${d.version}\`: ${d.license}`),
  '',
].join('\n');
writeFileSync(join(outDir, 'summary.md'), md);
console.log(md);
if (flagged.length) process.exitCode = 1;
